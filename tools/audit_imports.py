"""Read-only import/reference audit. Never loads binaries or claims ABI correctness."""
import argparse
import base64
from collections import Counter, defaultdict
import hashlib
import json
from pathlib import Path
import re


def nid(name):
    digest = hashlib.sha1(name.encode('ascii') + bytes.fromhex('518d64a635ded8c1e6b039b1c3e55230')).digest()[:8][::-1]
    return base64.b64encode(digest).decode().rstrip('=').replace('/', '-')


def registrations(text):
    """Exact scoped LIB_FUNCTION registrations; retain conflicting candidates."""
    pattern = r'LIB_FUNCTION\("([^"]+)",\s*"([^"]+)",\s*\d+,\s*"([^"]+)",\s*(?:ORBIS\()?([\w:]+)'
    return [(f'{n}#{lib}#{mod}', fn) for n, lib, mod, fn in re.findall(pattern, text)]


def audit(metadata, references, native, traces):
    imports = {}
    for path in metadata:
        for entry in json.loads(path.read_text())['imports']:
            imports[entry['name']] = entry
    exact, candidates, sources = defaultdict(set), defaultdict(set), defaultdict(set)
    signatures = defaultdict(set)
    source_count = 0
    for root in references:
        for path in sorted(root.rglob('*')):
            if not path.is_file() or path.suffix not in {'.cpp', '.c', '.h', '.hpp', '.inc'}:
                continue
            source_count += 1
            text = path.read_text(errors='replace')
            declarations = re.sub(r'/\*.*?\*/|//[^\n]*', '', text, flags=re.S)
            # Declaration facts only: omit bodies and do not reconstruct types.
            for declaration, fn in re.findall(r'(?:^|\n)([^\n{};=]*?\b((?:sce|posix_)[A-Za-z0-9_]+)\s*\([^{};]*?\))\s*(?:\{|;)', declarations):
                normalized = ' '.join(declaration.split())
                prefix = normalized.split(fn, 1)[0].strip()
                if prefix and not prefix.startswith(('return', 'if', 'else', 'case', 'throw', 'auto')) and len(normalized) < 1000:
                    signatures[fn].add(normalized)
            label = str(path.relative_to(root))
            for identity, fn in registrations(text):
                exact[identity].add(fn)
                sources[identity].add(label)
            # Candidate names from supplied implementations: hash evidence only,
            # never sufficient to infer library/module or a valid call signature.
            for fn in set(re.findall(r'\b(?:sce[A-Za-z0-9_]+|posix_[A-Za-z0-9_]+)\b', text)):
                candidates[nid(fn.removeprefix('posix_'))].add(fn)
            for fn in set(re.findall(r'(?:REG\(\s*|\{\s*)"([A-Za-z_][A-Za-z0-9_]*)"\s*,', declarations)):
                candidates[nid(fn)].add(fn)
    native_text = '\n'.join(p.read_text() for p in native.rglob('*') if p.is_file() and p.suffix in {'.cpp', '.inc'})
    observed, stopped = Counter(), Counter()
    for path in traces:
        for line in path.read_text(errors='replace').splitlines():
            try:
                event = json.loads(line)
            except ValueError:
                continue
            if event.get('event') == 'service-return':
                observed[event.get('name')] += 1
            if event.get('event') == 'unsupported-import':
                stopped[event.get('name')] += 1
    rows = []
    for identity in sorted(imports):
        names = sorted(exact[identity])
        evidence = 'scoped registration' if names else 'hash candidate' if candidates[identity.split('#')[0]] else 'unidentified'
        if not names:
            names = sorted(candidates[identity.split('#')[0]])
        # GPU manifests contain explicit names beside canonical identities.
        for line in native_text.splitlines():
            if f'"{identity}"' in line:
                match = re.search(r'//\s*(sce\w+)', line)
                if match:
                    names = sorted(set(names + [match[1]]))
                    if evidence == 'unidentified': evidence = 'native manifest'
        rows.append({'identity': identity, 'names': names, 'name_evidence': evidence,
                     'reference_signatures': sorted({s for name in names for s in signatures[name]}),
                     'reference_files': sorted(sources[identity]),
                     'native_literal': f'"{identity}"' in native_text,
                     'observed_returns': observed[identity], 'historical_stops': stopped[identity]})
    return {'source_files_scanned': source_count, 'imports': rows}


def markdown(report):
    rows = report['imports']
    counts = Counter(r['name_evidence'] for r in rows)
    groups = defaultdict(list)
    for row in rows:
        parts = row['identity'].split('#')
        groups[parts[1] if len(parts) == 3 else 'Unscoped symbols'].append(row)
    out = ['# System-call and import inventory', '',
           'Generated by `tools/audit_imports.py` from local metadata and supplied references.',
           'Imports include functions and data objects; they are not all kernel syscalls.', '',
           f"Scanned {report['source_files_scanned']} reference source files; inventoried {len(rows)} unique canonical imports.",
           ', '.join(f'{key}: {value}' for key, value in sorted(counts.items())) + '.', '',
           '**Evidence limits:** scoped registration establishes identity, not a correct implementation.',
           'Hash candidates do not prove scope or ABI. Native literal means source mentions the identity,',
           'not that support is complete. Recorded returns include errors and diagnostic behavior.',
           'Historical stops may already be fixed. No missing call is automatically bound.', '',
           'Private traces and executable metadata stay in ignored `out/`; this report contains interface facts only.', '']
    for library, entries in sorted(groups.items()):
        out += [f'## {library} ({len(entries)})', '', '| Canonical import | Name candidates | Evidence | Native literal | Returned in traces |', '|---|---|---|---|---|']
        for r in entries:
            out.append(f"| `{r['identity']}` | {', '.join(r['names']) or 'unknown'} | {r['name_evidence']} | {'yes' if r['native_literal'] else 'no'} | {'yes' if r['observed_returns'] else 'no'} |")
        out.append('')
        available = [r for r in entries if r['reference_signatures']]
        if available:
            out += ['Reference signatures below are implementation declarations, which may themselves be stubs or incomplete.', '']
            for row in available:
                out += [f"- `{row['identity']}`: " + '; '.join('`' + s.replace('|', '\\|') + '`' for s in row['reference_signatures'])]
            out.append('')
    return '\n'.join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--metadata', type=Path, action='append', required=True)
    parser.add_argument('--reference', type=Path, action='append', required=True)
    parser.add_argument('--native', type=Path, default=Path('native'))
    parser.add_argument('--trace-dir', type=Path)
    parser.add_argument('--json', type=Path, required=True)
    parser.add_argument('--markdown', type=Path, required=True)
    args = parser.parse_args()
    report = audit(args.metadata, args.reference, args.native,
                   sorted(args.trace_dir.glob('startup*.log')) if args.trace_dir else [])
    args.json.write_text(json.dumps(report, indent=2) + '\n')
    args.markdown.write_text(markdown(report))
    print(json.dumps({'source_files_scanned': report['source_files_scanned'],
                      'imports': len(report['imports']),
                      'evidence': dict(Counter(r['name_evidence'] for r in report['imports']))}))


if __name__ == '__main__':
    main()
